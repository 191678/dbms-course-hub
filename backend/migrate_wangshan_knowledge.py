def migrate_knowledge():
    db = next(get_db())
    
    print("正在清理现有数据...")
    db.execute(delete(Question))
    db.execute(delete(KnowledgePoint))
    db.execute(delete(Chapter))
    db.commit()
    print("现有数据清理完成")
    
    print("\n正在创建章节和知识点...")
    for chapter_id, chapter_data in wangshan_chapters.items():
        chapter = Chapter(
            id=chapter_id,
            title=chapter_data['title'],
            description=chapter_data['description'],
            order_index=chapter_id
        )
        db.add(chapter)
        
        for kp_data in chapter_data['knowledge_points']:
            kp = KnowledgePoint(
                chapter_id=chapter_id,
                content=kp_data['content'],
                difficulty=kp_data['difficulty'],
                category=kp_data['category'],
                detail_content=kp_data['detail_content'],
                key_points=kp_data['key_points'],
                order_index=kp_data['order_index']
            )
            db.add(kp)
        
        print(f"  创建章节 {chapter_id}: {chapter_data['title']} ({len(chapter_data['knowledge_points'])}个知识点)")
    
    db.commit()
    print("\n数据迁移完成！")
    
    print("\n验证数据：")
    chapters_count = db.query(Chapter).count()
    kp_count = db.query(KnowledgePoint).count()
    print(f"章节数量: {chapters_count}")
    print(f"知识点数量: {kp_count}")


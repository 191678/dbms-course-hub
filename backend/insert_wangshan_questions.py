import pymysql
import json

conn = pymysql.connect(host='localhost', user='root', password='mysql', database='dbms_course_hub', charset='utf8mb4')
cursor = conn.cursor()

cursor.execute('SELECT id, content FROM knowledge_points ORDER BY id')
knowledge_points = cursor.fetchall()
kp_map = {content: kp_id for kp_id, content in knowledge_points}

questions = []

def add_q(content, q_type, stem, options, answer, analysis, difficulty='medium'):
    kp_id = kp_map.get(content)
    if kp_id:
        opts = json.dumps(options, ensure_ascii=False) if options else None
        questions.append((kp_id, q_type, stem, opts, answer, analysis, difficulty))

